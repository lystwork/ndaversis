                      'code))\n'
                      '            \n'
                      '            for line in lines:\n'
                      '                stripped = line.strip()\n'
                      '                if not stripped:\n'
                      '                    features["metrics"]["blank_lines"] += 1\n'
                      '                elif stripped.startswith("#"):\n'
                      '                    features["metrics"]["comment_lines"] += 1\n'
                      '                else:\n'
                      '                    features["metrics"]["code_lines"] += 1\n'
                      '\n'
                      '            tree = ast.parse(code)\n'
                      '            module_docstring = ast.get_docstring(tree) or ""\n'
                      '            features["files"][filepath] = {"docstring": module_docstring}\n'
                      '            for node in ast.walk(tree):\n'
                      '                if isinstance(node, ast.ClassDef):\n'
                      '                    methods = {}\n'
                      '                    for item in node.body:\n'
                      '                        if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):\n'
                      '                            methods[item.name] = {\n'
                      '                                "args": [arg.arg for arg in item.args.args if arg.arg != '
                      '"self"],\n'
                      '                                "docstring": ast.get_docstring(item) or "",\n'
                      '                            }\n'
                      '                    method_names.update(methods.keys())\n'
                      '                    features["classes"][node.name] = {\n'
                      '                        "docstring": ast.get_docstring(node) or "",\n'
                      '                        "methods": methods\n'
                      '                    }\n'
                      '                elif isinstance(node, ast.Import):\n'
                      '                    for alias in node.names:\n'
                      '                        features["imports"].add(alias.name.split(\'.\')[0])\n'
                      '                elif isinstance(node, ast.ImportFrom) and node.module:\n'
                      '                    features["imports"].add(node.module.split(\'.\')[0])\n'
                      '                elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name '
                      'not in method_names:\n'
                      "                    # Only add if it's a top-level function (direct child of Module)\n"
                      '                    if any(module_item == node for module_item in tree.body):\n'
                      '                        docstring = ast.get_docstring(node)\n'
                      '                        features["functions"][node.name] = {\n'
                      '                            "args": [arg.arg for arg in node.args.args],\n'
                      '                            "docstring": docstring if docstring else "",\n'
                      '                        }\n'
                      '        except (SyntaxError, IOError, UnicodeDecodeError):\n'
                      '            pass\n'
                      '        return code\n'
