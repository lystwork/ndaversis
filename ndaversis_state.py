                      '    def _generate_diff(self, old_state: dict, new_state: dict) -> dict:\n'
                      '        """\n'
                      '        Generate a detailed diff between two repository states.\n'
                      '        Returns a dictionary mapping file paths to their change metrics.\n'
                      '        """\n'
                      '        diff_data = {}\n'
                      '        all_files = set(old_state.keys()) | set(new_state.keys())\n'
                      '        for file in sorted(all_files):\n'
                      '            old_c = old_state.get(file, "")\n'
                      '            new_c = new_state.get(file, "")\n'
                      '            if old_c == new_c:\n'
                      '                continue\n'
                      '\n'
                      '            metrics = {\n'
                      '                "status": "modified",\n'
                      '                "lines_added": 0, "lines_removed": 0,\n'
                      '                "chars_added": 0, "chars_removed": 0,\n'
                      '                "tabs_added": 0, "tabs_removed": 0,\n'
                      '                "spaces_added": 0, "spaces_removed": 0\n'
                      '            }\n'
                      '            if file not in old_state:\n'
                      '                metrics["status"] = "added"\n'
                      '            elif file not in new_state:\n'
                      '                metrics["status"] = "removed"\n'
                      '\n'
                      '            old_lines = old_c.splitlines()\n'
                      '            new_lines = new_c.splitlines()\n'
                      '            \n'
                      '            diff = list(difflib.ndiff(old_lines, new_lines))\n'
                      '            for line in diff:\n'
                      '                if line.startswith("+ "):\n'
                      '                    metrics["lines_added"] += 1\n'
                      '                    content = line[2:]\n'
                      '                    metrics["chars_added"] += len(content)\n'
                      '                    metrics["tabs_added"] += content.count("\\t")\n'
                      '                    metrics["spaces_added"] += content.count(" ")\n'
                      '                elif line.startswith("- "):\n'
                      '                    metrics["lines_removed"] += 1\n'
                      '                    content = line[2:]\n'
                      '                    metrics["chars_removed"] += len(content)\n'
                      '                    metrics["tabs_removed"] += content.count("\\t")\n'
                      '                    metrics["spaces_removed"] += content.count(" ")\n'
                      '                elif line.startswith("? "):\n'
                      '                    # ndiff highlights within-line changes with ? lines\n'
                      '                    pass\n'
                      '\n'
                      '            diff_data[file] = metrics\n'
                      '        return diff_data\n'
